function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <AuthProvider>
        <AppGuard>
          <Outlet />
        </AppGuard>
      </AuthProvider>
    </QueryClientProvider>
  );
}

function AppGuard({ children }: { children: ReactNode }) {
  const { isAuthenticated, isLoading } = useAuth();
  const router = useRouter();
  const pathname = router.state.location.pathname;

  const isAuthPage = pathname === "/login" || pathname === "/register";

  useEffect(() => {
    if (!isLoading) {
      if (!isAuthenticated && !isAuthPage) {
        router.navigate({ to: "/login" });
      } else if (isAuthenticated && isAuthPage) {
        router.navigate({ to: "/" });
      }
    }
  }, [pathname, isAuthenticated, isLoading, isAuthPage]);

  if (isLoading) {
    return (
      <div className="flex min-h-screen items-center justify-center bg-[#07090e] text-white font-sans">
        <div className="text-center">
          <div className="h-8 w-8 animate-spin rounded-full border-4 border-primary border-t-transparent mx-auto"></div>
          <p className="mt-4 text-sm text-muted-foreground">Loading Lumen...</p>
        </div>
      </div>
    );
  }

  if (!isAuthenticated && !isAuthPage) {
    return null;
  }

  if (isAuthenticated && isAuthPage) {
    return null;
  }

  return <>{children}</>;
}
